"""Идентификаторы доменных сущностей.

PlayerID — идентификатор игрока, то есть клиента, который присоединился
к игре. Численно он совпадает с идентификатором клиента: в адаптерах то
же число называется ClientID, в ядре — PlayerID. Имя показывает слой, а
переход ClientID → PlayerID делает прикладной слой, проверив, что клиент
действительно игрок.

Заведён через NewType, а не голый int: во время выполнения это ровно int
без каких-либо накладных расходов, но Pylance/Pyright ловит попытку
передать произвольный int (например, индекс каморы) туда, где ожидается
именно идентификатор игрока.
"""

from typing import NewType

PlayerID = NewType("PlayerID", int)
