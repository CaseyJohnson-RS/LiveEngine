"""Пределы каморного ряда.

MAX_SIZE — наибольшее число камор в ряду.

MAX_WEIGHT — наибольший вес одной каморы. Вес лежит в [1; MAX_WEIGHT]:
нижняя граница 1 — это базовый вес, без которого камору, куда никто
не положил фишек, нельзя было бы зарядить. Вес = базовый + фишки, а
фишек за раунд набирается не больше, чем камор в ряду, поэтому на
практике вес не превышает 1 + MAX_SIZE; MAX_WEIGHT оставлен с запасом.

Связь с сэмплером (engine/libs/weighted_subset_sampler/_limits.py).
Ряд передаёт сэмплеру и сами веса (расстановка, add_cartridge, shake),
и обратные им (remove_cartridge), то есть значения из
[1/MAX_WEIGHT; MAX_WEIGHT]. Поэтому пределы ряда обязаны помещаться
в пределы сэмплера:

    MAX_SIZE   <= MAX_SIZE сэмплера
    MAX_WEIGHT <= MAX_WEIGHT сэмплера

Иначе при допустимом для ряда вводе сэмплер бросит ошибку. Меняя
пределы, проверяйте обе стороны.
"""

MAX_WEIGHT = 100
MAX_SIZE = 20
