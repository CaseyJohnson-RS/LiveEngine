"""Конфигурация каморного ряда

Эти границы обеспечивают предсказуемое поведение игровой модели при
экстремальных входныхзначениях. Их можно менять, но осознано - см. пояснения
ниже.

MAX_WEIGHT — верхняя граница веса одной позиции. Она же задаёт и нижнюю
границу: поскольку модель должна быть симметрична относительно инвертирования
веса (обратная величина используется, например, при удалении патрона), вес
всегда лежит в диапазоне [1; MAX_WEIGHT]. Слишком большое
значение увеличивает разброс чисел с плавающей точкой внутри модели и
повышает риск потери точности при вычислениях.

MAX_SIZE — максимальный размер каморного ряда. Руководствуемся ограничениями
адекватности игры и ограничениями математической модели семплирования
(Weighted Subset Sampler)
"""

MAX_WEIGHT = 100
MAX_SIZE = 20
