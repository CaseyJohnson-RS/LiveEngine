"""Конфигурация математической модели семплирования.

Эти границы обеспечивают корректную работу модели на экстремальных входных
значениях. Их можно менять, но только вместе и осознанно — см. ниже.

MAX_WEIGHT — верхняя граница веса одной позиции. Она же задаёт и нижнюю
границу: поскольку модель симметрична относительно инвертирования веса, вес
всегда лежит в диапазоне [1/MAX_WEIGHT; MAX_WEIGHT].

MAX_SIZE — максимальный размер набора позиций, с которым работает модель.
Семплирование в худшем случае имеет сложность O(n^2) — оценка грубая, но
верная, — поэтому значение стоит выбирать с её учётом.

Связь границ. Каждая строка внутренней таблицы хранит значения
e_0..e_k элементарных симметрических многочленов весов, нормированные на
максимум строки. Максимум строки не больше суммы всех e_j, то есть
prod(1 + w_i) <= (1 + MAX_WEIGHT) ** MAX_SIZE, а e_0 = 1. Поэтому разброс
значений внутри строки растёт как (1 + MAX_WEIGHT) ** MAX_SIZE. Если он
выходит за диапазон double (значения меньше ~1e-323 обращаются в ноль),
модель молча начинает выдавать неверное распределение. Поэтому границы
обязаны удовлетворять

    (1 + MAX_WEIGHT) ** MAX_SIZE <= 1e300

(1e300 оставляет запас до порога обнуления и до зоны денормализованных
чисел, где теряется точность). Увеличивая одну границу, уменьшайте другую.
"""

MAX_WEIGHT = 1_000_000
MAX_SIZE = 40
